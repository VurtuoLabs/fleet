import * as React from "react";
import { cn } from "@/lib/utils";

/**
 * Card / Panel - the flat, bordered surface the console is built from. Matches
 * the mockup's <Panel>: surface background, hairline border, 4px radius.
 */
const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-lg border border-border bg-card text-card-foreground",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

